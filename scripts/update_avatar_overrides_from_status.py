#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Merge successful avatar fetch results from .cache/avatars/query_full_status.json
into src/data/avatarQueryOverrides.ts.

This is a small utility to solidify current successful results after an interrupted run.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict

REPO = Path(__file__).resolve().parents[1]
STATUS_FILE = REPO.parent / ".cache" / "avatars" / "query_full_status.json"
OVERRIDES_TS = REPO / "src" / "data" / "avatarQueryOverrides.ts"


def parse_existing_overrides_ts(text: str) -> Dict[str, Dict[str, str]]:
    blocks = re.findall(r"'(?P<id>\d+)':\s*\{(?P<body>[^}]*?)\}\s*,", text, flags=re.S)
    out: Dict[str, Dict[str, str]] = {}
    for sid, body in blocks:
        def pick(key: str) -> str:
            m = re.search(rf"{re.escape(key)}\s*:\s*'([^']*)'", body)
            return m.group(1) if m else ""

        out[sid] = {
            "uniqueId": pick("uniqueId"),
            "shortId": pick("shortId"),
            "displayId": pick("displayId"),
            "nickName": pick("nickName"),
            "profileUrl": pick("profileUrl"),
            "avatarUrl": pick("avatarUrl"),
        }
    return out


def esc_ts(v: str) -> str:
    return (v or "").replace("\\", "\\\\").replace("'", "\\'")


def main() -> int:
    if not STATUS_FILE.exists():
        raise SystemExit(f"status file not found: {STATUS_FILE}")
    status = json.loads(STATUS_FILE.read_text("utf-8"))
    ids = status.get("ids", {})

    text = OVERRIDES_TS.read_text("utf-8") if OVERRIDES_TS.exists() else ""
    existing = parse_existing_overrides_ts(text)

    added = 0
    updated = 0
    for sid, rec in ids.items():
        if not isinstance(rec, dict):
            continue
        if rec.get("status") != "ok":
            continue
        avatar_url = rec.get("avatarUrl")
        if not avatar_url:
            continue

        item = {
            "uniqueId": rec.get("uniqueId", ""),
            "shortId": rec.get("shortId", ""),
            "displayId": rec.get("uniqueId") or rec.get("shortId") or rec.get("nickCandidate") or "",
            "nickName": rec.get("nickName", ""),
            "profileUrl": rec.get("profileUrl") or (f"https://www.douyin.com/search/{rec.get('uniqueId') or rec.get('shortId') or ''}?type=user"),
            "avatarUrl": avatar_url,
        }

        if sid in existing:
            existing[sid].update({k: item[k] for k in item if item[k]})
            updated += 1
        else:
            existing[sid] = item
            added += 1

    # Replace the TS object only; keep header comments.
    header = "// Auto-generated by scripts/fetch_avatars_from_query.py\n// Do not edit manually.\n\nimport type { DouyinAvatarRecord } from './douyinAvatarMap';\n\n"

    meta = {
        "sourceStatusFile": str(STATUS_FILE),
        "mergedAt": __import__("time").strftime("%Y-%m-%d %H:%M:%S"),
        "totalOverrides": len(existing),
        "addedNow": added,
        "updatedNow": updated,
        "note": "固化中断任务的已成功头像（从 query_full_status.json 合入）",
    }

    lines = [header]
    lines.append("export const avatarQueryOverridesMeta = " + json.dumps(meta, ensure_ascii=False, indent=2) + " as const;\n")
    lines.append("export const avatarQueryOverrides: Record<string, DouyinAvatarRecord> = {\n")

    for sid in sorted(existing.keys(), key=lambda x: int(x)):
        rec = existing[sid]
        lines.append(f"  '{sid}': {{")
        lines.append(f"    uniqueId: '{esc_ts(rec.get('uniqueId',''))}',")
        lines.append(f"    shortId: '{esc_ts(rec.get('shortId',''))}',")
        lines.append(f"    displayId: '{esc_ts(rec.get('displayId',''))}',")
        lines.append(f"    nickName: '{esc_ts(rec.get('nickName',''))}',")
        lines.append(f"    profileUrl: '{esc_ts(rec.get('profileUrl',''))}',")
        lines.append(f"    avatarUrl: '{esc_ts(rec.get('avatarUrl',''))}',")
        lines.append("  },\n")

    lines.append("};\n")
    OVERRIDES_TS.write_text("".join(lines), encoding="utf-8")

    print(json.dumps({"added": added, "updated": updated, "total": len(existing)}, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
